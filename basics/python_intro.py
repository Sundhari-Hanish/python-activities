# variables and datatypes
# 1. What is a variable? Create a variable and print it.
name = "Sundhari"
print(name)
# Output:
# Sundhari


# 2. Create an integer variable and print its type.
age = 20
print(age)
print(type(age))
# Output:
# 20
# <class 'int'>


# 3. Create a float variable and print its type.
price = 99.99
print(price)
print(type(price))
# Output:
# 99.99
# <class 'float'>


# 4. Create a string variable and print it.
course = "Python Programming"
print(course)
print(type(course))
# Output:
# Python Programming
# <class 'str'>


# 5. Create a boolean variable and print it.
is_student = True
print(is_student)
print(type(is_student))
# Output:
# True
# <class 'bool'>


# 6. Create a list and print it.
fruits = ["Apple", "Banana", "Mango"]
print(fruits)
print(type(fruits))
# Output:
# ['Apple', 'Banana', 'Mango']
# <class 'list'>


# 7. Create a tuple and print it.
coordinates = (10, 20)
print(coordinates)
print(type(coordinates))

# Output:
# (10, 20)
# <class 'tuple'>


# 8. Create a dictionary and print it.
student = {
    "name": "Sundhari",
    "age": 20,
    "course": "Python"
}
print(student)
print(type(student))
# Output:
# {'name': 'Sundhari', 'age': 20, 'course': 'Python'}
# <class 'dict'>

